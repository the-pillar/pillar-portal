// Writes src/features/email/tokens.ts from the DESIGN.md tokens in
// src/app/globals.css, so an email's colors and font come from the one token
// source. Email clients ignore CSS variables and Tailwind, so the shell needs
// literal values; this file is where they live, and the only file under src/
// besides globals.css that `check:hex` lets hold a hex color.
//
// `var()` chains are resolved (`--primary` -> `var(--color-navy)` -> `#07253f`).
// With --check the file is not written: the script exits 1 when it is stale.
//
// Usage: node scripts/generate-email-tokens.mjs [--check] [--root <dir>]
//   --check  fail when tokens.ts differs from what globals.css gives
//   --root   project root (default: this repo; tests point it at a temp-dir
//            fixture)
import { mkdir, readFile, writeFile } from "node:fs/promises"
import path from "node:path"
import { parseArgs } from "node:util"

const { values: args } = parseArgs({
  options: { root: { type: "string" }, check: { type: "boolean" } },
})
const ROOT = path.resolve(args.root ?? path.join(import.meta.dirname, ".."))
const CSS_FILE = "src/app/globals.css"
const OUT_FILE = "src/features/email/tokens.ts"

// Output key -> custom property, and whether the value must be a hex color.
const TOKENS = [
  ["navy", "--color-navy", true],
  ["brandGold", "--color-brand-gold", true],
  ["canvas", "--color-canvas", true],
  ["white", "--color-white", true],
  ["foreground", "--foreground", true],
  ["mutedForeground", "--muted-foreground", true],
  ["primary", "--primary", true],
  ["primaryForeground", "--primary-foreground", true],
  ["fontSerif", "--font-serif", false],
]

const HEX = /^#[0-9a-f]{3,8}$/i

function declarations(css) {
  const withoutComments = css.replace(/\/\*[\s\S]*?\*\//g, "")
  const found = new Map()
  for (const match of withoutComments.matchAll(
    /(--[\w-]+)\s*:\s*([^;{}]+);/g
  )) {
    // The first declaration wins: @theme comes before :root.
    if (!found.has(match[1])) found.set(match[1], match[2].trim())
  }
  return found
}

function resolve(name, found, seen = []) {
  if (seen.includes(name)) {
    throw new Error(
      `${name} refers to itself (${[...seen, name].join(" -> ")})`
    )
  }
  const raw = found.get(name)
  if (raw === undefined)
    throw new Error(`${name} is not defined in ${CSS_FILE}`)
  return raw.replace(/var\(\s*(--[\w-]+)\s*\)/g, (_, inner) =>
    resolve(inner, found, [...seen, name])
  )
}

// Prettier's quote choice: double quotes unless that adds escapes.
function quote(value) {
  if (value.includes('"') && !value.includes("'")) return `'${value}'`
  return JSON.stringify(value)
}

function render(found) {
  const lines = TOKENS.map(([key, name, isColor]) => {
    const value = resolve(name, found)
    if (isColor && !HEX.test(value)) {
      throw new Error(`${name} resolves to "${value}", not a hex color`)
    }
    return `  ${key}: ${quote(isColor ? value.toLowerCase() : value)},`
  })
  return [
    `// Generated by scripts/generate-email-tokens.mjs from ${CSS_FILE}.`,
    "// Do not edit: change the token there and run `pnpm email:tokens`.",
    "// `pnpm check:email-tokens` fails when this file is stale.",
    "export const emailTokens = {",
    ...lines,
    "} as const",
    "",
  ].join("\n")
}

let output
try {
  output = render(
    declarations(await readFile(path.join(ROOT, CSS_FILE), "utf8"))
  )
} catch (error) {
  console.error(
    `email:tokens: ${error instanceof Error ? error.message : String(error)}`
  )
  process.exit(1)
}

const target = path.join(ROOT, OUT_FILE)

if (args.check) {
  const current = await readFile(target, "utf8").catch(() => null)
  if (current !== output) {
    console.error(
      `check:email-tokens: ${OUT_FILE} is stale. Run \`pnpm email:tokens\` and commit the result.`
    )
    process.exit(1)
  }
  console.log(`check:email-tokens: ${OUT_FILE} matches ${CSS_FILE}`)
} else {
  await mkdir(path.dirname(target), { recursive: true })
  await writeFile(target, output)
  console.log(`email:tokens: wrote ${OUT_FILE}`)
}
